#!/usr/bin/env node
// Generate prisma/schema.postgres.prisma from the canonical prisma/schema.prisma by
// swapping only the datasource block (sqlite → postgresql + directUrl for Supabase's
// pooler). Everything else — models, relations, indexes — is byte-identical, so the
// two schemas can never drift: this is generated, never hand-edited (ADR-004 rule).
//
// @req FR-030 — Postgres/Supabase readiness (ADR-007 P4).
// @spec docs/DB-MIGRATION-NOTES.md — same models, provider swap only.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const src = readFileSync(resolve(root, 'prisma/schema.prisma'), 'utf8')

const PG_DATASOURCE = `datasource db {
  provider  = "postgresql"
  url       = env("DATABASE_URL")
  directUrl = env("DIRECT_URL")
}`

// Replace the whole datasource db { ... } block, whatever its current provider.
const swapped = src.replace(/datasource\s+db\s*\{[^}]*\}/, PG_DATASOURCE)
if (!/provider\s*=\s*"postgresql"/.test(swapped)) {
  console.error('gen-postgres-schema: failed to swap the datasource block')
  process.exit(1)
}

const banner = `// GENERATED by scripts/gen-postgres-schema.mjs — DO NOT EDIT.
// Production (Supabase/Postgres) datasource. Regenerate with: npm run db:pg:schema
// The canonical schema is prisma/schema.prisma (SQLite, dev/test). Only the datasource
// differs; models/enums/indexes are identical (docs/DB-MIGRATION-NOTES.md).
`

mkdirSync(resolve(root, 'prisma/postgres'), { recursive: true })
writeFileSync(resolve(root, 'prisma/schema.postgres.prisma'), banner + '\n' + swapped)
console.log('wrote prisma/schema.postgres.prisma')
