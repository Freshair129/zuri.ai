// @req FR-094, FR-095 — a TOTP factor secret is sealed before it is stored and
//   opened only to verify a code.
// @spec SEC-029, SDD-096, ADR-088, SEC-018
// @tested tests/unit/identity/mfa-secret-seal.test.js
//
// This module is the whole encryption boundary for `MfaFactor.secret`: nothing
// else in the repository may create a cipher over that column. It imports only
// `node:crypto` on purpose, so an operator script can load it with plain `node`,
// and so the later shared credential-vault phase can replace the implementation
// behind these four exports without touching a caller.
//
// Stored form (every part base64url, joined with '.'):
//
//   mfa.v<keyVersion>.<nonce 12B>.<auth tag 16B>.<ciphertext>
//
// AES-256-GCM, a fresh nonce per seal, and additional authenticated data that
// binds the ciphertext to the key version, the Person and the factor row. A
// sealed value copied onto another factor, another Person, or relabelled with
// another key version fails authentication instead of opening.
//
// Keys come from the deployment, never the database:
//
//   ZURI_MFA_SECRET_KEY           64 hex chars — the current key; seals and opens
//   ZURI_MFA_SECRET_KEY_VERSION   positive integer, default 1 — its version label
//   ZURI_MFA_SECRET_KEY_V<n>      64 hex chars — a retired key, opens only
//
// Rotation: move the old key to ZURI_MFA_SECRET_KEY_V<old>, set the new key and
// version, deploy, then run `scripts/seal-mfa-factor-secrets.mjs --write`.
//
// In production a missing or malformed current key is a 503 before any factor is
// read or written (fail closed). Outside production a missing key falls back to a
// fixed development key labelled v0, and production refuses every v0 value — so a
// development database restored into production cannot open, rather than opening
// with a key that is published in this file.

import { createCipheriv, createDecipheriv, createHash, randomBytes } from 'node:crypto'

const PREFIX = 'mfa'
const ALGORITHM = 'aes-256-gcm'
const NONCE_BYTES = 12
const TAG_BYTES = 16
const HEX_KEY = /^[a-f0-9]{64}$/i
const LEGACY_BASE32 = /^[A-Z2-7]+=*$/
const SEALED = /^mfa\.v(0|[1-9]\d{0,5})\.([A-Za-z0-9_-]+)\.([A-Za-z0-9_-]+)\.([A-Za-z0-9_-]+)$/
const DEVELOPMENT_KEY_VERSION = 0
const DEVELOPMENT_KEY = createHash('sha256').update('zuri-ai:MfaFactor.secret:development-only').digest()

function sealError(code, reason) {
  const error = new Error(code)
  error.code = code
  error.status = 503
  if (reason) error.reason = reason
  return error
}

function isProduction(env) {
  return env.NODE_ENV === 'production'
}

/**
 * The keys this deployment may use. Throws MFA_SECRET_KEY_REQUIRED (503) in
 * production when the current key or its version label is missing or malformed.
 */
function resolveKeyring(env) {
  const raw = env.ZURI_MFA_SECRET_KEY
  const versionText = env.ZURI_MFA_SECRET_KEY_VERSION ?? '1'
  const production = isProduction(env)

  if (raw === undefined || raw === '') {
    if (production) throw sealError('MFA_SECRET_KEY_REQUIRED')
    return {
      current: { version: DEVELOPMENT_KEY_VERSION, key: DEVELOPMENT_KEY },
      keyFor: version => (version === DEVELOPMENT_KEY_VERSION ? DEVELOPMENT_KEY : retiredKey(env, version)),
    }
  }

  if (typeof raw !== 'string' || !HEX_KEY.test(raw) || !/^[1-9]\d{0,5}$/.test(String(versionText))) {
    throw sealError('MFA_SECRET_KEY_REQUIRED')
  }
  const current = { version: Number(versionText), key: Buffer.from(raw, 'hex') }
  return {
    current,
    keyFor(version) {
      if (version === current.version) return current.key
      if (version === DEVELOPMENT_KEY_VERSION) return production ? null : DEVELOPMENT_KEY
      return retiredKey(env, version)
    },
  }
}

function retiredKey(env, version) {
  const raw = env[`ZURI_MFA_SECRET_KEY_V${version}`]
  return typeof raw === 'string' && HEX_KEY.test(raw) ? Buffer.from(raw, 'hex') : null
}

function aad(version, { personId, factorId }) {
  if (typeof personId !== 'string' || !personId || typeof factorId !== 'string' || !factorId) {
    throw sealError('MFA_SECRET_BINDING_REQUIRED')
  }
  return Buffer.from(JSON.stringify(['MfaFactor.secret', version, personId, factorId]), 'utf8')
}

function parse(stored) {
  const match = typeof stored === 'string' ? SEALED.exec(stored) : null
  if (!match) return null
  return {
    version: Number(match[1]),
    nonce: Buffer.from(match[2], 'base64url'),
    tag: Buffer.from(match[3], 'base64url'),
    ciphertext: Buffer.from(match[4], 'base64url'),
  }
}

/**
 * Seal a base32 TOTP secret for storage on one factor row.
 *
 * @param {string} secret base32 secret as generated by generateTotpSecret()
 * @param {{ personId: string, factorId: string }} binding
 * @param {object} [env=process.env]
 * @returns {string} the stored form; never contains the secret
 */
export function sealMfaSecret(secret, binding, env = process.env) {
  if (typeof secret !== 'string' || !LEGACY_BASE32.test(secret)) throw sealError('MFA_SECRET_INVALID')
  const { current } = resolveKeyring(env)
  const nonce = randomBytes(NONCE_BYTES)
  const cipher = createCipheriv(ALGORITHM, current.key, nonce, { authTagLength: TAG_BYTES })
  cipher.setAAD(aad(current.version, binding))
  const ciphertext = Buffer.concat([cipher.update(secret, 'utf8'), cipher.final()])
  return [PREFIX, `v${current.version}`, ...[nonce, cipher.getAuthTag(), ciphertext].map(b => b.toString('base64url'))].join('.')
}

/**
 * Open a stored factor secret. Fails closed: a legacy plaintext value, an unknown
 * or retired-and-removed key version, a value bound to another row, or any
 * tampering throws MFA_SECRET_UNAVAILABLE (503) with a `reason`, never a secret.
 *
 * @param {string} stored
 * @param {{ personId: string, factorId: string }} binding
 * @param {object} [env=process.env]
 * @returns {string} base32 secret
 */
export function openMfaSecret(stored, binding, env = process.env) {
  const keyring = resolveKeyring(env)
  const parsed = parse(stored)
  if (!parsed) {
    throw sealError('MFA_SECRET_UNAVAILABLE', typeof stored === 'string' && LEGACY_BASE32.test(stored) ? 'LEGACY_PLAINTEXT' : 'UNRECOGNIZED')
  }
  const key = keyring.keyFor(parsed.version)
  if (!key) throw sealError('MFA_SECRET_UNAVAILABLE', 'KEY_VERSION_UNAVAILABLE')
  const additionalData = aad(parsed.version, binding)
  if (parsed.nonce.length !== NONCE_BYTES || parsed.tag.length !== TAG_BYTES) {
    throw sealError('MFA_SECRET_UNAVAILABLE', 'MALFORMED')
  }
  let secret
  try {
    const decipher = createDecipheriv(ALGORITHM, key, parsed.nonce, { authTagLength: TAG_BYTES })
    decipher.setAAD(additionalData)
    decipher.setAuthTag(parsed.tag)
    secret = Buffer.concat([decipher.update(parsed.ciphertext), decipher.final()]).toString('utf8')
  } catch {
    throw sealError('MFA_SECRET_UNAVAILABLE', 'AUTHENTICATION_FAILED')
  }
  if (!LEGACY_BASE32.test(secret)) throw sealError('MFA_SECRET_UNAVAILABLE', 'MALFORMED')
  return secret
}

/**
 * Classify a stored value without opening it — what the reseal sweep needs.
 * Also resolves the keyring, so a production deployment without a key fails here
 * before the sweep reads a row.
 *
 * @param {string} stored
 * @param {object} [env=process.env]
 * @returns {{ state: 'SEALED_CURRENT'|'SEALED_STALE'|'LEGACY_PLAINTEXT'|'UNRECOGNIZED', keyVersion: number|null, currentKeyVersion: number }}
 */
export function describeStoredMfaSecret(stored, env = process.env) {
  const { current } = resolveKeyring(env)
  const parsed = parse(stored)
  if (parsed) {
    return {
      state: parsed.version === current.version ? 'SEALED_CURRENT' : 'SEALED_STALE',
      keyVersion: parsed.version,
      currentKeyVersion: current.version,
    }
  }
  const legacy = typeof stored === 'string' && LEGACY_BASE32.test(stored)
  return { state: legacy ? 'LEGACY_PLAINTEXT' : 'UNRECOGNIZED', keyVersion: null, currentKeyVersion: current.version }
}

/**
 * Whether the configured keys are usable; throws the same 503 the seal and open
 * paths would. Lets a caller refuse before it deletes or writes anything.
 *
 * @param {object} [env=process.env]
 * @returns {number} current key version
 */
export function assertMfaSecretKeyConfigured(env = process.env) {
  return resolveKeyring(env).current.version
}
