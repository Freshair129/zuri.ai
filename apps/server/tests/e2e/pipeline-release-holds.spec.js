// @req FR-085 — persisted release explanation precedes Board/modal/status attempts.
// @spec ADR-035, BR-017, NFR-008
const {test,expect}=require('@playwright/test')
const {randomUUID}=require('node:crypto')
const {PrismaClient}=require('@prisma/client')
const {e2eTarget}=require('./e2e-target')
const {loginAsOwner}=require('./e2e-auth')
const db=new PrismaClient({datasources:{db:{url:e2eTarget().databaseUrl}}})
let project,ws,predecessor,item,gate,edge,foreignProject,foreignWs,foreignItem,foreignBusiness,foreignWorkspace
async function arrange(page,type='BLOCKS',legacy=false){
 await loginAsOwner(page);await page.getByRole('button',{name:/Open Business Business 01/}).click()
 const seed=await(await page.request.get('/api/resolve?type=PROJECT&code=PRJ-B01-TRANSFORM')).json()
 const base=await db.project.findUnique({where:{id:seed.id}})
 project=await db.project.create({data:{code:'C4-'+randomUUID(),name:'C4 isolated release',workspaceId:base.workspaceId,businessId:base.businessId}})
 ws=await db.workstream.create({data:{code:randomUUID(),name:'C4 isolated stream',projectId:project.id,executionMode:'SOFTWARE_SPRINT',progressStrategy:'TASK_WEIGHT'}})
 predecessor=await db.workItem.create({data:{code:randomUUID(),title:'C4 Drawing predecessor',subtype:'TASK',workstreamId:ws.id}})
 item=await db.workItem.create({data:{code:randomUUID(),title:'C4 Held successor',subtype:'TASK',workstreamId:ws.id}})
 gate=await db.gate.create({data:{code:randomUUID(),title:'C4 Acceptance',projectId:project.id,workstreamId:ws.id,status:'OPEN'}})
 // Arrangement only: C4 tests status/release through HTTP/UI, not the already
 // qualified C1 edge importer. A concurrent progress-cache refresh may correctly
 // stale an import preview, so do not make unrelated preview timing a fixture gate.
 edge=await db.dependency.create({data:{sourceType:'WORK_ITEM',sourceId:predecessor.id,targetType:'WORK_ITEM',targetId:item.id,dependencyType:type,contractJson:legacy?null:JSON.stringify({version:1,deliverable:'Signed drawing',acceptance:{kind:'GATE',gateId:gate.id}})}})
 await page.goto(`/projects/${project.id}/board`)
 await expect(page.locator(`[data-work-card="${item.id}"]`)).toBeVisible()
}
const card=page=>page.locator(`[data-work-card="${item.id}"]`)
async function open(page){await card(page).getByRole('button').first().focus();await page.keyboard.press('Enter');const dialog=page.getByRole('dialog');await expect(dialog).toBeVisible();return dialog}
test.beforeEach(()=>{project=ws=predecessor=item=gate=edge=foreignProject=foreignWs=foreignItem=foreignBusiness=foreignWorkspace=null})
test.afterEach(async()=>{
 if(edge)await db.dependency.deleteMany({where:{id:edge.id}})
 if(gate)await db.gate.deleteMany({where:{id:gate.id}})
 if(item||predecessor)await db.workItem.deleteMany({where:{id:{in:[item?.id,predecessor?.id].filter(Boolean)}}})
 if(ws)await db.workstream.deleteMany({where:{id:ws.id}})
 if(project)await db.project.deleteMany({where:{id:project.id}})
 if(foreignItem)await db.workItem.delete({where:{id:foreignItem.id}})
 if(foreignWs)await db.workstream.delete({where:{id:foreignWs.id}})
 if(foreignProject)await db.project.delete({where:{id:foreignProject.id}})
 if(foreignWorkspace)await db.workspace.delete({where:{id:foreignWorkspace.id}})
 if(foreignBusiness)await db.business.delete({where:{id:foreignBusiness.id}})
})
test.afterAll(()=>db.$disconnect())
test('held card shows predecessor link before keyboard opening; protected save refuses atomically',async({page})=>{
 await arrange(page);await expect(card(page).getByText('Release held',{exact:true})).toBeVisible()
 const link=card(page).getByRole('link',{name:predecessor.title});await expect(link).toHaveAttribute('href',`/projects/${project.id}/board`)
 const dialog=await open(page);await expect(dialog.getByText('Release held',{exact:true})).toBeVisible()
 await dialog.getByRole('combobox',{name:/Status/}).selectOption('DONE')
 const saved=page.waitForResponse(r=>r.request().method()==='PATCH'&&r.url().endsWith('/api/work/'+item.id))
 await dialog.getByRole('button',{name:'Save',exact:true}).click();expect((await saved).status()).toBe(409)
 await expect(dialog.getByRole('alert')).toContainText('Release is held');expect((await db.workItem.findUnique({where:{id:item.id}})).status).toBe('PLANNED')
 await dialog.getByRole('combobox',{name:/Status/}).selectOption('BLOCKED');await dialog.getByRole('button',{name:'Save',exact:true}).click();await expect(dialog).not.toBeVisible()
 expect((await db.workItem.findUnique({where:{id:item.id}})).status).toBe('BLOCKED')
})
test('finish-only permits starting; stale acceptance refuses finish then reload releases it',async({page})=>{
 await arrange(page,'FINISH_BEFORE');let dialog=await open(page)
 await dialog.getByRole('combobox',{name:/Status/}).selectOption('IN_PROGRESS');await dialog.getByRole('button',{name:'Save',exact:true}).click();await expect(dialog).not.toBeVisible()
 await db.gate.update({where:{id:gate.id},data:{status:'PASSED'}});await page.reload();await expect(card(page).getByText('Release held',{exact:true})).toHaveCount(0)
 dialog=await open(page);await db.gate.update({where:{id:gate.id},data:{status:'OPEN'}})
 await dialog.getByRole('combobox',{name:/Status/}).selectOption('DONE');await dialog.getByRole('button',{name:'Save',exact:true}).click();await expect(dialog.getByRole('alert')).toContainText('Release is held')
 await expect(dialog.getByText('Release held',{exact:true})).toBeVisible();await db.gate.update({where:{id:gate.id},data:{status:'WAIVED'}})
 await dialog.getByRole('button',{name:'Reload release',exact:true}).click();await expect(dialog.getByText('Release held',{exact:true})).toHaveCount(0)
 await dialog.getByRole('button',{name:'Save',exact:true}).click();await expect(dialog).not.toBeVisible();expect((await db.workItem.findUnique({where:{id:item.id}})).status).toBe('DONE')
})
test('legacy null creates no hold; keyboard StatusSelect remains the equivalent status path',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.emulateMedia({reducedMotion:'reduce'});await arrange(page,'BLOCKS',true)
 await expect(card(page).getByText('Release held',{exact:true})).toHaveCount(0)
 await page.goto(`/projects/${project.id}/all-work`)
 const row=page.getByRole('row').filter({hasText:item.code});const select=row.getByRole('combobox',{name:'work status'})
 await select.focus();await page.keyboard.press('d');await page.keyboard.press('Enter');await expect(select).toHaveValue('DONE');expect((await db.workItem.findUnique({where:{id:item.id}})).status).toBe('DONE')
})
test('restricted predecessor metadata never appears on the real Board projection',async({page})=>{
 await arrange(page)
 const original=await db.project.findUnique({where:{id:project.id},include:{business:true}})
 foreignBusiness=await db.business.create({data:{code:randomUUID(),name:'Private C4 business',tenantId:original.business.tenantId}})
 foreignWorkspace=await db.workspace.create({data:{code:randomUUID(),name:'Private C4 workspace',businessId:foreignBusiness.id,tenantId:original.business.tenantId,scopeType:'BUSINESS'}})
 foreignProject=await db.project.create({data:{code:randomUUID(),name:'Private C4 project',workspaceId:foreignWorkspace.id,businessId:foreignBusiness.id}})
 foreignWs=await db.workstream.create({data:{code:randomUUID(),name:'Private C4 stream',projectId:foreignProject.id,executionMode:'SOFTWARE_SPRINT',progressStrategy:'TASK_WEIGHT'}})
 foreignItem=await db.workItem.create({data:{code:randomUUID(),title:'SECRET-C4-PREDECESSOR',subtype:'TASK',workstreamId:foreignWs.id}})
 await db.dependency.update({where:{id:edge.id},data:{sourceId:foreignItem.id}})
 const response=await page.request.get('/api/work/'+item.id);expect(await response.json()).toEqual({held:true,blockers:[],truncated:false,restricted:true})
 await page.reload();await expect(card(page).getByText('Waiting for restricted handoff evidence.')).toBeVisible()
 await expect(card(page).getByRole('link')).toHaveCount(0);await expect(page.getByText('SECRET-C4-PREDECESSOR',{exact:true})).toHaveCount(0)
 const denied=await page.request.patch('/api/work/'+item.id,{data:{status:'DONE'}});expect(denied.status()).toBe(404)
})
test('StatusSelect explains held work before refusing an illegal keyboard selection',async({page})=>{
 await arrange(page);await page.goto(`/projects/${project.id}/all-work`)
 const row=page.getByRole('row').filter({hasText:item.code});await expect(row.getByText('Release held',{exact:true})).toBeVisible()
 const select=row.getByRole('combobox',{name:'work status'});await select.focus();await page.keyboard.press('i');await page.keyboard.press('Enter')
 await expect(row.getByRole('alert')).toContainText('Release is held');await expect(select).toHaveValue('PLANNED')
})

test('a stale unheld StatusSelect refreshes predecessor explanation after the server refuses',async({page})=>{
 await arrange(page);await db.gate.update({where:{id:gate.id},data:{status:'PASSED'}})
 await page.goto(`/projects/${project.id}/all-work`)
 const row=page.getByRole('row').filter({hasText:item.code});await expect(row.getByRole('combobox',{name:'work status'})).toHaveValue('PLANNED');await expect(row.getByText('Release held',{exact:true})).toHaveCount(0)
 await db.gate.update({where:{id:gate.id},data:{status:'OPEN'}})
 await row.getByRole('combobox',{name:'work status'}).selectOption('IN_PROGRESS')
 await expect(row.getByRole('alert')).toContainText('Release is held')
 await expect(row.getByRole('link',{name:predecessor.title})).toBeVisible()
})
test('protected modal Save waits for the pre-attempt release read',async({page})=>{
 await arrange(page)
 let resume;const held=new Promise(resolve=>{resume=resolve})
 await page.route('**/api/work/'+item.id,async route=>{if(route.request().method()==='GET')await held;await route.continue()})
 try {
  const dialog=await open(page);await expect(dialog.getByText('Checking handoff release…')).toBeVisible()
  await dialog.getByRole('combobox',{name:/Status/}).selectOption('DONE')
  await expect(dialog.getByRole('button',{name:'Save',exact:true})).toBeDisabled()
 } finally {resume()}
})
