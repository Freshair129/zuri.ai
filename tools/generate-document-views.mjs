import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { readCanonicalRegistry } from './document-registry.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const GENERATOR_VERSION = '1.0.0';
const SOURCE_RELATIONS = new Set([
  'specifies', 'specified_by', 'decided_by', 'relates', 'relates_to',
  'references', 'depends_on', 'follows', 'supersedes', 'superseded_by',
]);

function toPosix(value) {
  return value.split(sep).join('/');
}

function outputPath(fromPath, toPath) {
  const value = toPosix(relative(dirname(fromPath), toPath));
  return encodeURI(value).replaceAll('(', '%28').replaceAll(')', '%29');
}

function link(fromPath, toPath, label) {
  return `[${String(label).replaceAll('\\', '\\\\').replaceAll('[', '\\[').replaceAll(']', '\\]')}](${outputPath(fromPath, toPath)})`;
}

function inlineCode(value) {
  const runs = [...String(value).matchAll(/`+/g)].map((match) => match[0].length);
  const fence = '`'.repeat(Math.max(0, ...runs) + 1);
  const pad = String(value).startsWith('`') || String(value).endsWith('`') ? ' ' : '';
  return `${fence}${pad}${value}${pad}${fence}`;
}

function rebaseStatementLinks(statement, root, sourcePath, viewPath) {
  return String(statement).replace(/(!?\[[^\]]*\]\()(<[^>]+>|(?:\\.|[^)\s])+)(\))/g, (_match, open, target, close) => {
    const wrapped = target.startsWith('<') && target.endsWith('>');
    const destination = wrapped ? target.slice(1, -1) : target;
    if (/^[a-z][a-z0-9+.-]*:/i.test(destination) || destination.startsWith('//') || destination.startsWith('/')) {
      return `${open}${target}${close}`;
    }

    const suffixAt = destination.search(/[?#]/);
    const sourceName = suffixAt < 0 ? destination : destination.slice(0, suffixAt);
    const suffix = suffixAt < 0 ? '' : destination.slice(suffixAt);
    const sourceTarget = sourceName === '' ? sourcePath : resolve(root, dirname(sourcePath), decodeURIComponent(sourceName));
    const rootRelativeTarget = toPosix(relative(root, sourceTarget));
    if (rootRelativeTarget === '..' || rootRelativeTarget.startsWith('../')
      || rootRelativeTarget.split('/').some((part) => part === '.brain' || part === 'private')) {
      const labelStart = open.indexOf('[') + 1;
      const labelEnd = open.lastIndexOf('](');
      return open.slice(labelStart, labelEnd);
    }
    const rebased = `${outputPath(viewPath, rootRelativeTarget)}${suffix}`;
    return `${open}${wrapped ? `<${rebased}>` : rebased}${close}`;
  });
}

function renderSourceCell(record, root, viewPath) {
  return rebaseStatementLinks(recordFinalCell(record), root, record.sourcePath, viewPath);
}

function blockquote(value) {
  return String(value).split(/\r?\n/).map((line) => `> ${line}`).join('\n');
}

function recordFinalCell(record) {
  return record.cells.slice(1, -1).at(-1) ?? '';
}

function pathOf(node) {
  return node?.path ?? node?.canonical_path;
}

function localNodePath(root, node, purpose) {
  const path = pathOf(node);
  if (typeof path !== 'string' || path === '' || path.includes('\\') || path.startsWith('/')) {
    throw new Error(`${purpose} graph node ${node?.id ?? '(unknown)'} has no repository-relative path`);
  }
  if (path.split('/').some((part) => part === '.brain' || part === 'private')) return undefined;
  const absolute = resolve(root, path);
  const rootPrefix = `${resolve(root)}${sep}`;
  if (absolute !== resolve(root) && !absolute.startsWith(rootPrefix)) {
    throw new Error(`${purpose} graph path escapes the repository root: ${path}`);
  }
  return existsSync(absolute) ? path : undefined;
}

function requiredNodePath(root, node, purpose) {
  const path = localNodePath(root, node, purpose);
  if (!path) throw new Error(`${purpose} graph path does not exist: ${pathOf(node)}`);
  return path;
}

function markdownHeader(metadata) {
  return [
    '---',
    'doc_type: generated-view',
    `view_type: ${metadata.viewType}`,
    `generator_version: "${GENERATOR_VERSION}"`,
    `version: "${GENERATOR_VERSION}"`,
    `registry_source_revision: ${metadata.registrySourceRevision}`,
    `graph_version: "${metadata.graphVersion}"`,
    'status: generated',
    '---',
    '',
    '> Generated projection. Edit canonical records or source documents, then regenerate; do not edit this file.',
    '',
  ].join('\n');
}

function nodeTitle(node) {
  return node.title ?? node.label ?? node.id;
}

function plainLinkLabel(value) {
  return String(value)
    .replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/`([^`]*)`/g, '$1');
}

function checkGraph(root, records, graph) {
  if (!graph || typeof graph !== 'object' || !/^2\./.test(String(graph.version ?? ''))) {
    throw new Error(`Unsupported or missing document graph version: ${graph?.version ?? '(missing)'}`);
  }
  if (!Array.isArray(graph.nodes) || !Array.isArray(graph.edges)) {
    throw new Error('Document graph must contain nodes and edges arrays');
  }

  const nodes = new Map();
  for (const node of graph.nodes) {
    if (!node || typeof node.id !== 'string' || nodes.has(node.id)) {
      throw new Error(`Document graph has a missing or duplicate node ID: ${node?.id ?? '(missing)'}`);
    }
    nodes.set(node.id, node);
  }

  const byId = new Map(records.map((record) => [record.id, record]));
  const features = records.filter((record) => record.family === 'FEAT');
  for (const feature of features) {
    const featureNode = nodes.get(`feat:${feature.id}`);
    if (!featureNode || featureNode.type !== 'feature' || featureNode.namespace !== 'ZAI') {
      throw new Error(`Document graph is missing the ZAI feature node ${feature.id}`);
    }
    if (featureNode.canonical_path !== feature.path) {
      throw new Error(`${feature.id} canonical path differs between registry and graph`);
    }
    requiredNodePath(root, featureNode, 'Feature');

    const expected = new Set(feature.requirementKeys);
    for (const requirementId of expected) {
      const requirement = byId.get(requirementId);
      const requirementNode = nodes.get(`req:${requirementId}`);
      if (!requirement || requirement.family !== 'FR') {
        throw new Error(`${feature.id} names missing canonical requirement ${requirementId}`);
      }
      if (!requirementNode || requirementNode.type !== 'requirement' || requirementNode.namespace !== 'ZAI') {
        throw new Error(`Document graph is missing the ZAI requirement node ${requirementId}`);
      }
      if (requirementNode.canonical_path !== requirement.path) {
        throw new Error(`${requirementId} canonical path differs between registry and graph`);
      }
      requiredNodePath(root, requirementNode, 'Requirement');
      const bundled = graph.edges.some((edge) => edge.from === featureNode.id
        && edge.to === requirementNode.id
        && edge.type === 'bundles'
        && edge.source === 'feature-registry'
        && edge.status === 'current');
      if (!bundled) throw new Error(`${feature.id} is missing current bundles edge for ${requirementId}`);
    }

    const actual = new Set(graph.edges
      .filter((edge) => edge.from === featureNode.id && edge.type === 'bundles' && edge.source === 'feature-registry')
      .map((edge) => edge.to?.replace(/^req:/, '')));
    if (actual.size !== expected.size || [...actual].some((id) => !expected.has(id))) {
      throw new Error(`${feature.id} graph membership differs from its canonical FR list`);
    }
  }

  return { nodes, byId, features };
}

function requirementSourceLinks(root, viewPath, requirement, graph, nodes) {
  const requirementNodeId = `req:${requirement.id}`;
  const unique = new Map();
  for (const edge of graph.edges) {
    if (!SOURCE_RELATIONS.has(edge.type) || (edge.from !== requirementNodeId && edge.to !== requirementNodeId)) continue;
    const otherId = edge.from === requirementNodeId ? edge.to : edge.from;
    const node = nodes.get(otherId);
    if (!node || !['document', 'adr', 'appendix'].includes(node.type)) continue;
    const path = pathOf(node);
    if (!path || path === requirement.path) continue;
    const resolved = localNodePath(root, node, 'Source');
    if (!resolved) continue;
    const key = `${resolved}\0${edge.type}\0${edge.source ?? ''}\0${edge.status ?? ''}`;
    unique.set(key, { node, path: resolved, edge });
  }
  return [...unique.values()].sort((left, right) => left.path.localeCompare(right.path)
    || left.edge.type.localeCompare(right.edge.type)
    || String(left.edge.source ?? '').localeCompare(String(right.edge.source ?? '')));
}

function renderDesign(root, feature, records, graph, nodes, registrySourceRevision) {
  const viewPath = `docs/features/${feature.id}/design.md`;
  const lines = [
    markdownHeader({ viewType: 'feature-design', registrySourceRevision, graphVersion: graph.version }),
    `# ${feature.id} — ${rebaseStatementLinks(feature.statement, root, feature.sourcePath, viewPath)}`,
    '',
    `Feature record: ${link(viewPath, feature.path, `ZAI:${feature.id} canonical record`)}.`,
    '',
    '**Source row final cell (display projection; full row in canonical record):**',
    '',
    blockquote(renderSourceCell(feature, root, viewPath)),
    '',
    '## Included requirements',
    '',
  ];

  for (const requirementId of feature.requirementKeys) {
    const requirement = records.find((record) => record.id === requirementId);
    if (!requirement) throw new Error(`${feature.id} has no loaded record for ${requirementId}`);
    lines.push(
      `### ${link(viewPath, requirement.path, `ZAI:${requirement.id} canonical record`)}`,
      '',
      blockquote(rebaseStatementLinks(requirement.statement, root, requirement.sourcePath, viewPath)),
      '',
      '**Source row final cell (display projection; full row in canonical record):**',
      '',
      blockquote(renderSourceCell(requirement, root, viewPath)),
      '**Existing source/design/context links** (graph navigation; the relation is not new evidence):',
    );
    const sources = requirementSourceLinks(root, viewPath, requirement, graph, nodes);
    if (sources.length === 0) {
      lines.push('', 'No typed source/context document edge is present in the frozen graph.', '');
      continue;
    }
    for (const source of sources) {
      const provenance = [source.edge.type, source.edge.source, source.edge.status]
        .filter(Boolean).map(inlineCode).join(' · ');
      lines.push(`- ${link(viewPath, source.path, nodeTitle(source.node))} — ${provenance}`);
    }
    lines.push('');
  }

  lines.push('## Limits', '',
    'This view summarizes the preserved canonical statements and markers. It adds no acceptance criteria, requirement IDs, approval, ownership, or delivery evidence.', '');
  return lines.join('\n');
}

function requirementBindings(root, requirement, graph, nodes) {
  const requirementNodeId = `req:${requirement.id}`;
  const bindings = [];
  for (const edge of graph.edges) {
    const node = nodes.get(edge.from);
    const kind = edge.type === 'implements' && node?.type === 'code_file'
      ? 'code'
      : edge.type === 'verifies' && node?.type === 'test' ? 'test' : undefined;
    if (!kind || edge.to !== requirementNodeId || edge.status !== 'current') continue;
    const path = requiredNodePath(root, node, `${kind === 'code' ? 'Code' : 'Test'} binding`);
    bindings.push({ kind, path, type: edge.type, source: edge.source ?? 'unspecified' });
  }
  const unique = new Map(bindings.map((binding) => [
    `${binding.kind}\0${binding.path}\0${binding.type}\0${binding.source}`,
    binding,
  ]));
  return [...unique.values()].sort((left, right) => left.kind.localeCompare(right.kind)
    || left.path.localeCompare(right.path)
    || left.source.localeCompare(right.source));
}

function renderVerification(root, feature, records, graph, nodes, registrySourceRevision) {
  const viewPath = `docs/features/${feature.id}/verification.md`;
  const lines = [
    markdownHeader({ viewType: 'feature-verification', registrySourceRevision, graphVersion: graph.version }),
    `# ${feature.id} — verification bindings`,
    '',
    '> Graph bindings are traceability paths only. This page reports no test execution or pass result and does not invent AC or TC records.',
    '',
  ];

  for (const requirementId of feature.requirementKeys) {
    const requirement = records.find((record) => record.id === requirementId);
    if (!requirement) throw new Error(`${feature.id} has no loaded record for ${requirementId}`);
    lines.push(`## ${link(viewPath, requirement.path, `ZAI:${requirement.id}`)}`, '');
    const bindings = requirementBindings(root, requirement, graph, nodes);
    for (const kind of ['code', 'test']) {
      const kindBindings = bindings.filter((binding) => binding.kind === kind);
      lines.push(`### ${kind === 'code' ? 'Code paths' : 'Test paths'} — graph bindings`, '');
      if (kindBindings.length === 0) {
        lines.push('No current binding of this type is present in the frozen graph.', '');
        continue;
      }
      for (const binding of kindBindings) {
        lines.push(`- ${link(viewPath, binding.path, binding.path)} — ${inlineCode(binding.type)} (${inlineCode(binding.source)})`);
      }
      lines.push('');
    }
  }

  lines.push('## Limits', '',
    'A listed path records a current graph relationship, not proof that a test ran, passed, or covers an acceptance criterion. Check the linked source and execute the relevant tests separately.', '');
  return lines.join('\n');
}

function categoryMatch(category, path) {
  const lower = path.toLowerCase();
  switch (category) {
    case 'product':
      return ['docs/product/', 'docs/domains/'].some((prefix) => lower.startsWith(prefix))
        || ['docs/product.md', 'docs/prd-sdd-v1.0.md', 'docs/features.md', 'docs/gap-analysis-zuri-govibe.md'].includes(lower);
    case 'architecture':
      return lower === 'docs/architecture.md'
        || lower.startsWith('docs/architecture-')
        || lower.startsWith('docs/architecture/')
        || lower.startsWith('docs/decisions/adr-');
    case 'operations':
      return ['docs/runbooks/', 'docs/deployment/', 'docs/migrations/', 'docs/roadmap/', 'docs/plans/']
        .some((prefix) => lower.startsWith(prefix));
    case 'governance':
      return ['docs/appendices/', 'docs/templates/', 'docs/change-requests/', 'docs/changes/', 'docs/governance/']
        .some((prefix) => lower.startsWith(prefix))
        || lower === 'docs/governance-link-metadata.md'
        || lower === 'docs/decisions/adr-039-document-identity-and-stability.md';
    default:
      return false;
  }
}

function renderCategoryIndex(root, category, graph, registrySourceRevision, features) {
  const viewPath = `docs/${category}/README.md`;
  const heading = category[0].toUpperCase() + category.slice(1);
  const candidates = graph.nodes
    .filter((node) => ['document', 'adr', 'appendix'].includes(node.type) && node.status === 'current')
    .map((node) => ({ node, path: pathOf(node) }))
    .filter(({ path }) => typeof path === 'string' && categoryMatch(category, path))
    .sort((left, right) => left.path.localeCompare(right.path));

  const deduplicated = new Map();
  for (const item of candidates) {
    const path = localNodePath(root, item.node, `${heading} index`);
    if (!path) continue;
    deduplicated.set(path, item.node);
  }
  const lines = [
    markdownHeader({ viewType: `${category}-navigation`, registrySourceRevision, graphVersion: graph.version }),
    `# ${heading} documentation`,
    '',
    `Generated navigation for current source documents in the ${category} grouping. A path's presence here does not declare ownership or approval.`,
    '',
  ];
  for (const [path, node] of deduplicated) lines.push(`- ${link(viewPath, path, nodeTitle(node))}`);
  if (deduplicated.size === 0) lines.push('No current source documents match this grouping in the frozen graph.');

  if (category === 'product') {
    lines.push('', '## Feature views', '');
    for (const feature of features) {
      const featureView = `docs/features/${feature.id}/design.md`;
      lines.push(`- ${link(viewPath, featureView, `${feature.id} — ${plainLinkLabel(feature.statement)}`)}`);
    }
  }
  lines.push('');
  return lines.join('\n');
}

export function renderDocumentViews({ root = ROOT, records = readCanonicalRegistry(root), graph }) {
  const normalizedRoot = resolve(root);
  const inputGraph = graph ?? JSON.parse(readFileSync(join(normalizedRoot, 'docs/.doc-graph.json'), 'utf8'));
  const { nodes, byId, features } = checkGraph(normalizedRoot, records, inputGraph);
  const registrySourceRevision = records[0]?.registrySourceRevision
    ?? records.find((record) => record.status === 'source-preserved')?.sourceRevision
    ?? records[0]?.sourceRevision;
  if (!registrySourceRevision || !/^[a-f0-9]{40}$/i.test(registrySourceRevision)) {
    throw new Error('Canonical registry index has no valid source revision');
  }
  if (records.some((record) => record.status === 'source-preserved' && record.sourceRevision !== registrySourceRevision)) {
    throw new Error('Source-preserved canonical records do not match the registry source revision');
  }
  if (records.some((record) => record.status === 'reviewed-migration'
      && (!/^[a-f0-9]{40}$/i.test(record.migrationBaseRevision || '') || !record.migrationDocument))) {
    throw new Error('Reviewed migration records require separate base-revision and approval-document provenance');
  }

  const outputs = new Map();
  for (const feature of features) {
    outputs.set(`docs/features/${feature.id}/design.md`, renderDesign(normalizedRoot, feature, records, inputGraph, nodes, registrySourceRevision));
    outputs.set(`docs/features/${feature.id}/verification.md`, renderVerification(normalizedRoot, feature, records, inputGraph, nodes, registrySourceRevision));
  }
  for (const category of ['product', 'architecture', 'operations', 'governance']) {
    outputs.set(`docs/${category}/README.md`, renderCategoryIndex(normalizedRoot, category, inputGraph, registrySourceRevision, features));
  }
  return outputs;
}

export function writeDocumentViews(root, outputs, check = false) {
  const normalizedRoot = resolve(root);
  for (const [relativePath, content] of outputs) {
    if (relativePath.includes('\\') || relativePath.startsWith('/') || relativePath.split('/').includes('..')) {
      throw new Error(`Unsafe generated view path: ${relativePath}`);
    }
    const destination = join(normalizedRoot, relativePath);
    if (check) {
      if (!existsSync(destination)) throw new Error(`${relativePath} is missing; run generator without --check`);
      if (readFileSync(destination, 'utf8') !== content) throw new Error(`${relativePath} is stale; run generator without --check`);
    } else {
      mkdirSync(dirname(destination), { recursive: true });
      writeFileSync(destination, content, 'utf8');
    }
  }
  return outputs.size;
}

function parseArgs(args) {
  const result = { root: ROOT, graph: undefined, check: false };
  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === '--check') result.check = true;
    else if (arg === '--root' || arg === '--graph') {
      const value = args[index + 1];
      if (!value || value.startsWith('--')) throw new Error(`${arg} requires a path`);
      result[arg.slice(2)] = value;
      index += 1;
    } else {
      throw new Error('Usage: node tools/generate-document-views.mjs [--check] [--root <path>] [--graph <path>]');
    }
  }
  result.root = resolve(result.root);
  if (result.graph) result.graph = isAbsolute(result.graph) ? resolve(result.graph) : resolve(result.root, result.graph);
  return result;
}

const args = process.argv.slice(2);
if (import.meta.url === pathToFileURL(resolve(process.argv[1] ?? '')).href) {
  try {
    const options = parseArgs(args);
    const graph = JSON.parse(readFileSync(options.graph ?? join(options.root, 'docs/.doc-graph.json'), 'utf8'));
    const records = readCanonicalRegistry(options.root);
    const outputs = renderDocumentViews({ root: options.root, records, graph });
    const count = writeDocumentViews(options.root, outputs, options.check);
    const features = records.filter((record) => record.family === 'FEAT').length;
    console.log(`${options.check ? 'Verified' : 'Generated'} ${count} document views for ${features} features using graph ${graph.version}.`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
